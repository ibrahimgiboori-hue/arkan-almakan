      perform private.fn_transaction_register_move(tx,'approval_route',s.requested_by_user_id,null,s.target_portal_key,s.target_user_id,null,null,null,s.request_reason,'approval_step',s.id::text,'approval_step:'||s.id::text||':route',jsonb_build_object('step_order',s.step_order,'action_type',s.action_type,'target_group_key',s.target_group_key,'target_capability',s.target_capability,'backfilled',true));
