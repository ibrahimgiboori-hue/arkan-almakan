create or replace function private.fn_transaction_destination_from_module(p_module text)
returns text language sql stable set search_path=public,private,pg_temp as $$
  select case
    when p_module='hr' then 'workforce'
    when exists(select 1 from public.procedure_destinations d where d.destination_key=p_module and d.is_active) then p_module
    else null end;
$$;

create or replace function private.fn_transaction_key_from_approval(p_source_table text,p_transaction_type text)
returns text language plpgsql stable set search_path=public,private,pg_temp as $$
declare v_key text;
begin
  v_key:=private.fn_transaction_key_for_source(p_source_table);
  if v_key is not null then return v_key; end if;
  v_key:=case p_transaction_type when 'quotation_review' then 'quotation' when 'timesheet_week' then 'project_timesheet' else p_transaction_type end;
  if exists(select 1 from public.transaction_definitions where transaction_key=v_key and is_active) then return v_key; end if;
  return null;
end;
$$;

create or replace function private.fn_transaction_register_ensure(
  p_transaction_key text,p_source_table text,p_source_id uuid,p_source_destination_key text default null,
  p_origin_user_id uuid default null,p_project_id uuid default null,p_metadata jsonb default '{}'::jsonb
)
returns uuid language plpgsql security definer set search_path=public,private,pg_temp as $$
declare v_id uuid;
begin
  if p_transaction_key is null or p_source_table is null or p_source_id is null then return null; end if;
  if not exists(select 1 from public.transaction_definitions where transaction_key=p_transaction_key and is_active) then return null; end if;
  if p_source_destination_key is not null and not exists(select 1 from public.procedure_destinations where destination_key=p_source_destination_key and is_active) then p_source_destination_key:=null; end if;
  insert into public.transaction_register(transaction_key,source_table,source_id,source_destination_key,origin_user_id,project_id,current_destination_key,metadata)
  values(p_transaction_key,p_source_table,p_source_id,p_source_destination_key,p_origin_user_id,p_project_id,p_source_destination_key,coalesce(p_metadata,'{}'::jsonb))
  on conflict (transaction_key,source_table,source_id) do update
  set source_destination_key=coalesce(public.transaction_register.source_destination_key,excluded.source_destination_key),
      origin_user_id=coalesce(public.transaction_register.origin_user_id,excluded.origin_user_id),
      project_id=coalesce(public.transaction_register.project_id,excluded.project_id),
      current_destination_key=coalesce(public.transaction_register.current_destination_key,excluded.current_destination_key),
      metadata=public.transaction_register.metadata||excluded.metadata,
      updated_at=now()
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function private.fn_transaction_register_move(
  p_transaction_id uuid,p_movement_kind text,p_actor_user_id uuid default null,p_from_destination_key text default null,
  p_to_destination_key text default null,p_target_user_id uuid default null,p_actor_destination_key text default null,
  p_decision_destination_key text default null,p_decision_key text default null,p_note text default null,
  p_source_engine text default 'system',p_source_engine_ref text default null,p_source_event_ref text default null,
  p_payload jsonb default '{}'::jsonb,p_lifecycle_status text default null
)
returns uuid language plpgsql security definer set search_path=public,private,pg_temp as $$
declare v_tx public.transaction_register%rowtype; v_id uuid; v_from text; v_now timestamptz:=now();
begin
  if p_transaction_id is null or nullif(trim(coalesce(p_movement_kind,'')),'') is null then return null; end if;
  if p_source_event_ref is not null then
    select id into v_id from public.transaction_movements where source_event_ref=p_source_event_ref;
    if v_id is not null then return v_id; end if;
  end if;
  select * into v_tx from public.transaction_register where id=p_transaction_id for update;
  if not found then return null; end if;
  v_from:=coalesce(p_from_destination_key,v_tx.current_destination_key,v_tx.source_destination_key);
  insert into public.transaction_movements(transaction_id,movement_kind,from_destination_key,to_destination_key,actor_destination_key,decision_destination_key,actor_user_id,target_user_id,decision_key,note,source_engine,source_engine_ref,source_event_ref,payload,created_at)
  values(p_transaction_id,p_movement_kind,v_from,p_to_destination_key,coalesce(p_actor_destination_key,v_from),p_decision_destination_key,p_actor_user_id,p_target_user_id,p_decision_key,p_note,coalesce(nullif(p_source_engine,''),'system'),p_source_engine_ref,p_source_event_ref,coalesce(p_payload,'{}'::jsonb),v_now)
  returning id into v_id;
  update public.transaction_register
  set current_destination_key=coalesce(p_to_destination_key,current_destination_key),
      current_user_id=case when p_lifecycle_status in ('closed','cancelled') then null when p_to_destination_key is not null then p_target_user_id else current_user_id end,
      lifecycle_status=coalesce(p_lifecycle_status,lifecycle_status),
      closed_at=case when p_lifecycle_status in ('closed','cancelled') then coalesce(closed_at,v_now) else closed_at end,
      last_movement_at=v_now,updated_at=v_now
  where id=p_transaction_id;
  return v_id;
end;
$$;

