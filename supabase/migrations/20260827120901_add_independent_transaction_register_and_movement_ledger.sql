    if w.status<>'pending' then
      life:=case when w.status in ('approved','rejected') then 'closed' when w.status='cancelled' then 'cancelled' else 'open' end;
      perform private.fn_transaction_register_move(tx,'approval_status',null,null,case when w.status='returned' then src else null end,null,null,case when w.status='returned' then src else null end,w.status,w.return_note,'approval',w.id::text,'approval_workflow:'||w.id::text||':status:'||w.status||':'||w.version_no::text,jsonb_build_object('workflow_no',w.workflow_no,'status',w.status,'backfilled',true),life);
    end if;
  end loop;
end $$;

-- Backfill existing work items and their event history.
do $$
declare t public.workspace_tasks%rowtype; e public.workspace_task_events%rowtype; tx uuid; src text; dest text; kind text; life text;
begin
  for t in select * from public.workspace_tasks order by created_at loop
    tx:=private.fn_transaction_id_for_workspace_task(t); if tx is null then continue; end if;
    src:=coalesce(t.source_portal_key,t.portal_key); dest:=coalesce(t.target_portal_key,t.current_destination_key,src);
    kind:=case when t.communication_kind='inquiry' then 'inquiry' when t.task_type='request' then 'request' else 'assignment' end;
    perform private.fn_transaction_register_move(tx,kind,t.creator_user_id,src,dest,t.assignee_user_id,src,null,null,t.description,'workspace_task',t.id::text,'workspace_task:'||t.id::text||':created',jsonb_build_object('title',t.title,'priority',t.priority,'task_type',t.task_type,'communication_kind',t.communication_kind,'backfilled',true));
    for e in select * from public.workspace_task_events where task_id=t.id order by created_at,id loop
      life:=case when e.event_type='closed' then 'closed' when e.event_type='cancelled' then 'cancelled' when e.event_type='completed' then 'completed' else null end;
      perform private.fn_transaction_register_move(tx,'work_'||e.event_type,e.actor_user_id,null,coalesce(t.current_destination_key,t.target_portal_key),e.subject_user_id,null,null,e.to_status,e.note,'workspace_event',e.id::text,'workspace_event:'||e.id::text,jsonb_build_object('from_status',e.from_status,'to_status',e.to_status,'progress',e.progress,'document_id',e.document_id,'backfilled',true),life);
    end loop;
  end loop;
end $$;
