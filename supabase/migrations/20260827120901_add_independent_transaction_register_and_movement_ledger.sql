create or replace function public.fn_transaction_journey(p_transaction_id uuid default null,p_transaction_no text default null,p_source_table text default null,p_source_id uuid default null)
returns jsonb language plpgsql stable security definer set search_path=public,private,pg_temp as $$
declare v_tx public.transaction_register%rowtype; v_uid uuid:=auth.uid(); v_allowed boolean:=false; v_moves jsonb;
begin
  if v_uid is null then raise exception 'يجب تسجيل الدخول'; end if;
  select * into v_tx from public.transaction_register t
  where (p_transaction_id is not null and t.id=p_transaction_id)
     or (p_transaction_no is not null and t.transaction_no=p_transaction_no)
     or (p_source_table is not null and p_source_id is not null and t.source_table=p_source_table and t.source_id=p_source_id)
  order by case when p_transaction_id is not null and t.id=p_transaction_id then 1 when p_transaction_no is not null and t.transaction_no=p_transaction_no then 2 else 3 end limit 1;
  if not found then return null; end if;
  v_allowed:=public.fn_is_primary_user() or v_tx.origin_user_id=v_uid or v_tx.current_user_id=v_uid
    or exists(select 1 from public.transaction_movements m where m.transaction_id=v_tx.id and (m.actor_user_id=v_uid or m.target_user_id=v_uid))
    or exists(select 1 from public.transaction_movements m join public.v_my_capabilities c on c.capability_key=(m.payload->>'target_capability') where m.transaction_id=v_tx.id and nullif(m.payload->>'target_capability','') is not null);
  if not v_allowed then raise exception 'لا تملك صلاحية عرض مسار هذه المعاملة'; end if;
  select coalesce(jsonb_agg(to_jsonb(m) order by m.movement_seq),'[]'::jsonb) into v_moves from public.transaction_movements m where m.transaction_id=v_tx.id;
  return jsonb_build_object('transaction',to_jsonb(v_tx),'movements',v_moves);
end;
$$;
