export const EXTERNAL_ATTENDANCE_STATUS = Object.freeze({
  UPLOADED:'uploaded',
  PARSED:'parsed',
  CALIBRATED:'calibrated',
  ANALYZED:'analyzed',
  JUSTIFICATIONS:'justifications',
  RECALCULATED:'recalculated',
  READY_TO_POST:'ready_to_post',
  CLOSED:'closed',
  FAILED:'failed',
  SUPERSEDED:'superseded',
});

export const EXTERNAL_ATTENDANCE_SEQUENCE = Object.freeze([
  EXTERNAL_ATTENDANCE_STATUS.UPLOADED,
  EXTERNAL_ATTENDANCE_STATUS.PARSED,
  EXTERNAL_ATTENDANCE_STATUS.CALIBRATED,
  EXTERNAL_ATTENDANCE_STATUS.ANALYZED,
  EXTERNAL_ATTENDANCE_STATUS.JUSTIFICATIONS,
  EXTERNAL_ATTENDANCE_STATUS.RECALCULATED,
  EXTERNAL_ATTENDANCE_STATUS.READY_TO_POST,
  EXTERNAL_ATTENDANCE_STATUS.CLOSED,
]);

const TRANSITIONS = Object.freeze({
  [EXTERNAL_ATTENDANCE_STATUS.UPLOADED]:Object.freeze([
    EXTERNAL_ATTENDANCE_STATUS.PARSED,
    EXTERNAL_ATTENDANCE_STATUS.FAILED,
  ]),
  [EXTERNAL_ATTENDANCE_STATUS.PARSED]:Object.freeze([
    EXTERNAL_ATTENDANCE_STATUS.CALIBRATED,
    EXTERNAL_ATTENDANCE_STATUS.FAILED,
    EXTERNAL_ATTENDANCE_STATUS.SUPERSEDED,
  ]),
  [EXTERNAL_ATTENDANCE_STATUS.CALIBRATED]:Object.freeze([
    EXTERNAL_ATTENDANCE_STATUS.ANALYZED,
    EXTERNAL_ATTENDANCE_STATUS.FAILED,
  ]),
  [EXTERNAL_ATTENDANCE_STATUS.ANALYZED]:Object.freeze([
    EXTERNAL_ATTENDANCE_STATUS.JUSTIFICATIONS,
    EXTERNAL_ATTENDANCE_STATUS.RECALCULATED,
  ]),
  [EXTERNAL_ATTENDANCE_STATUS.JUSTIFICATIONS]:Object.freeze([
    EXTERNAL_ATTENDANCE_STATUS.RECALCULATED,
  ]),
  [EXTERNAL_ATTENDANCE_STATUS.RECALCULATED]:Object.freeze([
    EXTERNAL_ATTENDANCE_STATUS.READY_TO_POST,
  ]),
  [EXTERNAL_ATTENDANCE_STATUS.READY_TO_POST]:Object.freeze([
    EXTERNAL_ATTENDANCE_STATUS.CLOSED,
  ]),
  [EXTERNAL_ATTENDANCE_STATUS.CLOSED]:Object.freeze([]),
  [EXTERNAL_ATTENDANCE_STATUS.FAILED]:Object.freeze([]),
  [EXTERNAL_ATTENDANCE_STATUS.SUPERSEDED]:Object.freeze([]),
});

export function externalAttendanceStageIndex(status) {
  return EXTERNAL_ATTENDANCE_SEQUENCE.indexOf(String(status || ''));
}

export function canTransitionExternalAttendance(fromStatus,toStatus) {
  const allowed=TRANSITIONS[String(fromStatus || '')] || [];
  return allowed.includes(String(toStatus || ''));
}

export function isExternalAttendanceTerminal(status) {
  return [
    EXTERNAL_ATTENDANCE_STATUS.CLOSED,
    EXTERNAL_ATTENDANCE_STATUS.FAILED,
    EXTERNAL_ATTENDANCE_STATUS.SUPERSEDED,
  ].includes(String(status || ''));
}

export function externalAttendanceTransitionsFrom(status) {
  return [...(TRANSITIONS[String(status || '')] || [])];
}
