export const ALL_RECRUITMENT_PROFILES=[...CONSTRUCTION_JOB_CATALOG];
const normalize=(s='')=>String(s).replace(/[ـ]/g,'').replace(/\s+/g,' ').replace(/\s*و\s*/g,'و').trim().toLowerCase();
export function matchRecruitmentProfile(title,profileKey){
 if(profileKey){const p=getJobProfile(profileKey)||ALL_RECRUITMENT_PROFILES.find(x=>x.key===profileKey);if(p)return p;}
 const t=normalize(title); const exact=ALL_RECRUITMENT_PROFILES.find(x=>normalize(x.title)===t); if(exact)return exact;
 const words=t.split(' ').filter(x=>x.length>2); let best=null,bestScore=0;
 for(const p of ALL_RECRUITMENT_PROFILES){const pt=normalize(p.title);const score=words.filter(w=>pt.includes(w)).length;if(score>bestScore){best=p;bestScore=score;}}
 return bestScore>=1?best:null;
}
export function recommendedQuestions(profile,targetLevel='entry'){
 const level=LEVEL_LABELS[targetLevel]?targetLevel:'entry';
 if(profile?.family==='procurement'||/عقد|عقود|مطالبات/.test(profile?.title||'')) return CONTRACTS[level]();
 return genericQuestions(profile,level);
}
